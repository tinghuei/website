export interface User {
  id: string;
  name: string;
  email: string;
  password: string;
  role: 'employee' | 'manager' | 'admin' | 'hr';
  department: string;
  managerId?: string;
  avatar: string;
  joinDate: string;
}

export interface QuizQuestion {
  id: string;
  question: string;
  options: string[];
  answerIndex: number;
}

export interface Course {
  id: string;
  title: string;
  description: string;
  category: string;
  instructor: string;
  duration: number;
  mandatory: boolean;
  thumbnail: string;
  passingScore: number;
  status: 'active' | 'inactive';
  createdAt: string;
  quizQuestions: QuizQuestion[];
  videoId?: string; // YouTube video ID (可由管理員在後台設定)
  localVideo?: boolean; // 是否已上傳本機影片檔（儲存於目前瀏覽器的 IndexedDB）
  localPresentation?: boolean; // 是否已上傳課程簡報/教材檔（儲存於目前瀏覽器的 IndexedDB）
  presentationName?: string; // 簡報/教材檔案名稱
  videoTranscript?: string; // 影片內容文字稿/大綱，由課程建立者貼上，供 AI 測驗生成器依實際影片內容出題
  externalVideoUrl?: string; // 外部免費影片連結（例如 YouTube 完整網址），用於免費課程庫直接觀看
}

export interface CourseAssignment {
  id: string;
  userId: string;
  courseId: string;
  assignedBy: string;
  assignedByName: string;
  assignedAt: string;
  dueDate?: string;
  note?: string;
}

export interface Enrollment {
  id: string;
  userId: string;
  courseId: string;
  status: 'in_progress' | 'pending_review' | 'completed' | 'rejected';
  progressPercent: number;
  watchTimeMinutes: number;
  enrolledAt: string;
  reportSubmitted: boolean;
  surveySubmitted: boolean;
  quizSubmitted: boolean;
  quizScore: number | null;
  reviewStatus: 'pending' | 'approved' | 'rejected' | null;
  certificateIssued: boolean;
  managerComment: string | null;
  submittedAt?: string;
  completedAt?: string;
  reportContent?: string;
  surveyData?: Record<string, number | string>;
  videoWatched?: boolean;
  managerApproved?: boolean;   // 主管審核通過
  hrApproved?: boolean;        // 人資審核通過
  managerApprovedAt?: string;
  hrApprovedAt?: string;
  managerApprovedBy?: string;
  hrApprovedBy?: string;
}

export interface Discussion {
  id: string;
  courseId: string;
  userId: string;
  userName: string;
  message: string;
  timestamp: string;
}

export interface Notification {
  id: string;
  userId: string;
  type: string;
  message: string;
  read: boolean;
  createdAt: string;
}

export interface AuditLog {
  id: string;
  userId: string;
  userName: string;
  action: string;
  target: string;
  details: string;
  timestamp: string;
}

